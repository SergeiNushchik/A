    // ===== ПОИСК БЛИЖАЙШИХ ПО ГЕОЛОКАЦИИ =====
    fun findNearestShops(userLat: Double, userLng: Double, limit: Int = 20): List<RepairShop> {
        return allShops.map { shop ->
            shop.copy(distanceKm = calculateDistance(userLat, userLng, shop.lat, shop.lng))
        }.sortedBy { it.distanceKm }
            .take(limit)
    }

    // Формула гаверсинусов для расчета расстояния между двумя точками (км)
    private fun calculateDistance(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val r = 6371.0
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val a = sin(dLat / 2).pow(2) +
                cos(Math.toRadians(lat1)) * cos(Math.toRadians(lat2)) *
                sin(dLon / 2).pow(2)
        val c = 2 * atan2(sqrt(a), sqrt(1 - a))
        return r * c
    }

    fun findShopsByService(query: String): List<RepairShop> {
        val queryLower = query.lowercase()

        val matchedServices = mutableSetOf<String>()
        serviceKeywords.forEach { (keyword, services) ->
            if (queryLower.contains(keyword)) {
                matchedServices.addAll(services)
            }
        }

        val result = if (matchedServices.isNotEmpty()) {
            allShops.filter { shop ->
                shop.services.any { service ->
                    matchedServices.any { matchedService ->
                        service.contains(matchedService, ignoreCase = true)
                    }
                }
            }
        } else {
            val words = query.split(" ", "(", ")", "—", "-").filter { it.length > 2 }
            allShops.filter { shop ->
                words.any { word ->
                    shop.services.any { service ->
                        service.contains(word, ignoreCase = true)
                    } || shop.name.contains(word, ignoreCase = true)
                }
            }
        }

        return result.ifEmpty {
            allShops.sortedByDescending { it.rating }.take(5)
        }
    }

    fun findShopsByCategory(category: String): List<RepairShop> {
        return allShops.filter { shop ->
            shop.services.any { service ->
                service.contains(category, ignoreCase = true)
            }
        }
    }
